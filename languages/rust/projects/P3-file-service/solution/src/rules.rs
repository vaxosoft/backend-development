//! Pure rules about names, ids and ETags.

/// Longest file name (in characters) that is kept.
pub const MAX_NAME_CHARS: usize = 100;

/// Turns the client-supplied file name into a harmless display name.
/// It is only ever shown to clients; it is never used as a path.
pub fn sanitize_filename(raw: &str) -> String {
    let base = raw.rsplit(['/', '\\']).next().unwrap_or_default();
    let mut name: String = base
        .chars()
        .filter(|c| !c.is_control())
        .map(|c| if c == '"' { '_' } else { c })
        .collect();
    while name.contains("..") {
        name = name.replace("..", ".");
    }
    let name: String = name.trim().chars().take(MAX_NAME_CHARS).collect();
    if name.is_empty() || name == "." {
        "file".to_owned()
    } else {
        name
    }
}

/// Ids are generated by us: 32 lowercase hex characters.
pub fn is_valid_id(id: &str) -> bool {
    id.len() == 32 && id.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
}

/// Does an `If-None-Match` value (`*`, weak validators, lists) match this file?
pub fn etag_matches(if_none_match: &str, sha256: &str) -> bool {
    let etag = format!("\"{sha256}\"");
    if_none_match.split(',').map(str::trim).any(|candidate| {
        candidate == "*" || candidate.strip_prefix("W/").unwrap_or(candidate) == etag
    })
}

/// `attachment; filename="<name>"`, with non-ASCII characters replaced by `_`.
pub fn content_disposition(name: &str) -> String {
    let ascii: String = name
        .chars()
        .map(|c| {
            if c.is_ascii() && !c.is_ascii_control() {
                c
            } else {
                '_'
            }
        })
        .collect();
    format!("attachment; filename=\"{ascii}\"")
}
